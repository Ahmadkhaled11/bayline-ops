"""Goods that each merchant sends, with usual parcel weights and declared values."""

from typing import NamedTuple


class Product(NamedTuple):
    """One line of a merchant's range. Weights and values are for one piece."""

    description: str
    category: str
    max_pieces: int
    piece_kg: tuple[float, float]
    piece_egp: tuple[int, int]


def _p(description, category, max_pieces, low_kg, high_kg, low_egp, high_egp):
    return Product(description, category, max_pieces, (low_kg, high_kg), (low_egp, high_egp))


